package net.studioblueplanet.ttbin;

import java.io.ByteArrayOutputStream;
import net.studioblueplanet.usb.UsbFile;

/**
 * Builds synthetic ttbin files for testing. This avoids committing real
 * ttbin files containing real GPS positions. The coordinates generated are
 * fictitious.
 * Note: the status, heart rate and indoor cycling records contain local time,
 * the GPS records UTC time, like the files generated by the watch.
 * @author jorgen
 */
public class TtbinTestFileBuilder
{
    // Record lengths, including tag, as defined in the header of real files
    private static final int[][]    RECORDLENGTHS=
    {
        {0x21,  7}, {0x22, 28}, {0x23, 24}, {0x25,  7}, {0x27, 18}, {0x2f, 11},
        {0x30,  3}, {0x32, 17}, {0x40, 12}, {0x42,  2}, {0x49,  5}
    };

    private final ByteArrayOutputStream bytes;
    private final int                   timeZoneSeconds;

    /**
     * Constructor. Creates the header
     * @param startTimeUtc Start time of the activity, epoch seconds UTC
     * @param timeZoneSeconds Local time offset with respect to UTC in seconds
     */
    public TtbinTestFileBuilder(long startTimeUtc, int timeZoneSeconds)
    {
        int i;

        this.bytes          =new ByteArrayOutputStream();
        this.timeZoneSeconds=timeZoneSeconds;

        writeInt(0x20, 1);                              // tag
        writeInt(0x0A, 2);                              // file version
        writeInt(1, 2); writeInt(7, 2); writeInt(64, 2);// firmware version
        writeInt(0x0E, 2);                              // product ID
        writeInt(startTimeUtc+timeZoneSeconds, 4);      // start time, local
        writeString("1.7.64", 16);                      // software version
        writeString("synthetic", 80);                   // GPS firmware version
        writeInt(startTimeUtc+timeZoneSeconds, 4);      // watch time
        writeInt(timeZoneSeconds, 4);                   // local time offset
        writeInt(0, 1);                                 // reserved
        writeInt(RECORDLENGTHS.length, 1);              // record length count
        for (i=0; i<RECORDLENGTHS.length; i++)
        {
            writeInt(RECORDLENGTHS[i][0], 1);
            writeInt(RECORDLENGTHS[i][1], 2);
        }
    }

    /**
     * Write integer value as little endian
     * @param value Value to write
     * @param size Number of bytes
     */
    private void writeInt(long value, int size)
    {
        int i;
        for (i=0; i<size; i++)
        {
            bytes.write((int)((value>>(8*i))&0xff));
        }
    }

    /**
     * Write float value as little endian
     * @param value Value to write
     */
    private void writeFloat(float value)
    {
        writeInt(Float.floatToIntBits(value)&0xffffffffL, 4);
    }

    /**
     * Write zero padded string
     * @param value String to write
     * @param size Size of the field in bytes
     */
    private void writeString(String value, int size)
    {
        int i;
        for (i=0; i<size; i++)
        {
            bytes.write(i<value.length()?value.charAt(i):0);
        }
    }

    /**
     * Add a status record (tag 0x21)
     * @param status Status, see TtbinFileDefinition STATUS_...
     * @param activity Activity type, see TtbinFileDefinition ACTIVITY_...
     * @param timeUtc Time, epoch seconds UTC
     * @return This builder
     */
    public TtbinTestFileBuilder addStatus(int status, int activity, long timeUtc)
    {
        writeInt(TtbinFileDefinition.TAG_STATUS, 1);
        writeInt(status, 1);
        writeInt(activity, 1);
        writeInt(timeUtc+timeZoneSeconds, 4);
        return this;
    }

    /**
     * Add a GPS record (tag 0x22)
     * @param timeUtc Time, epoch seconds UTC
     * @param lat Latitude in degrees
     * @param lon Longitude in degrees
     * @param calories Cumulative calories
     * @param distance Cumulative distance in m
     * @return This builder
     */
    public TtbinTestFileBuilder addGps(long timeUtc, double lat, double lon, int calories, float distance)
    {
        writeInt(TtbinFileDefinition.TAG_GPS, 1);
        writeInt(Math.round(lat*1.0E7), 4);
        writeInt(Math.round(lon*1.0E7), 4);
        writeInt(0, 2);                                 // heading
        writeInt(300, 2);                               // speed cm/s
        writeInt(timeUtc, 4);
        writeInt(calories, 2);
        writeFloat(3.0f);                               // instantaneous speed
        writeFloat(distance);
        writeInt(0, 1);                                 // cycles
        return this;
    }

    /**
     * Add a heart rate record (tag 0x25)
     * @param timeUtc Time, epoch seconds UTC
     * @param heartRate Heart rate in bpm
     * @return This builder
     */
    public TtbinTestFileBuilder addHeartRate(long timeUtc, int heartRate)
    {
        writeInt(TtbinFileDefinition.TAG_HEART_RATE, 1);
        writeInt(heartRate, 1);
        writeInt(255, 1);                               // external sensor
        writeInt(timeUtc+timeZoneSeconds, 4);
        return this;
    }

    /**
     * Add an indoor cycling record (tag 0x40). Content is not used.
     * @param timeUtc Time, epoch seconds UTC
     * @return This builder
     */
    public TtbinTestFileBuilder addIndoorCycling(long timeUtc)
    {
        writeInt(TtbinFileDefinition.TAG_INDOOR_CYCLING, 1);
        writeInt(timeUtc+timeZoneSeconds, 4);
        writeInt(0, 4);
        writeInt(0, 3);
        return this;
    }

    /**
     * Add a lap record (tag 0x2f)
     * @param elapsedSeconds Cumulative time in s
     * @param distance Cumulative distance in m
     * @param calories Cumulative calories
     * @return This builder
     */
    public TtbinTestFileBuilder addLap(int elapsedSeconds, float distance, int calories)
    {
        writeInt(TtbinFileDefinition.TAG_LAP, 1);
        writeInt(elapsedSeconds, 4);
        writeFloat(distance);
        writeInt(calories, 2);
        return this;
    }

    /**
     * Add the summary record (tag 0x27)
     * @param activity Activity type
     * @param distance Total distance in m
     * @param duration Total duration in s
     * @param calories Total calories
     * @return This builder
     */
    public TtbinTestFileBuilder addSummary(int activity, float distance, int duration, int calories)
    {
        writeInt(TtbinFileDefinition.TAG_SUMMARY, 1);
        writeInt(activity, 1);
        writeFloat(distance);
        writeInt(duration, 4);
        writeInt(calories, 2);
        writeInt(0, 6);
        return this;
    }

    /**
     * Returns the file as UsbFile, as read from the watch
     * @return The file
     */
    public UsbFile toUsbFile()
    {
        byte[] data=bytes.toByteArray();
        return new UsbFile(0xFFFFFFFF, data.length, data);
    }

    /* ******************************************************************************************* *\
     * PREDEFINED TEST FILES
    \* ******************************************************************************************* */
    public static final long        STARTTIME   =1790000000L;   // 2026-09-21T14:13:20Z
    public static final int         TIMEZONE    =3600;

    /**
     * Running activity of 600 s with a record each second. Lap marks after
     * 200, 400 and 500 records. Distance 3 m/s, calories 1 per 5 s, heart
     * rate 100+i/10 bpm for record i.
     * If withPause, the activity is paused for 60 s after record 299.
     * @param withPause Insert a pause in the second lap
     * @return The ttbin file
     */
    public static UsbFile createRunWithLaps(boolean withPause)
    {
        TtbinTestFileBuilder    builder;
        long                    time;
        int                     i;

        builder=new TtbinTestFileBuilder(STARTTIME, TIMEZONE);
        builder.addStatus(TtbinFileDefinition.STATUS_READY , TtbinFileDefinition.ACTIVITY_RUNNING, STARTTIME);
        builder.addStatus(TtbinFileDefinition.STATUS_ACTIVE, TtbinFileDefinition.ACTIVITY_RUNNING, STARTTIME);
        time=STARTTIME;
        for (i=0; i<600; i++)
        {
            if (withPause && i==300)
            {
                builder.addStatus(TtbinFileDefinition.STATUS_PAUSED, TtbinFileDefinition.ACTIVITY_RUNNING, time);
                time+=60;
                builder.addStatus(TtbinFileDefinition.STATUS_ACTIVE, TtbinFileDefinition.ACTIVITY_RUNNING, time);
            }
            builder.addGps(time, 10.0+i*1.0E-5, 20.0, i/5, 3.0f*i);
            builder.addHeartRate(time, 100+i/10);
            if (i==199)
            {
                builder.addLap(200, 600.0f, 40);
            }
            else if (i==399)
            {
                builder.addLap(400, 1200.0f, 80);
            }
            else if (i==499)
            {
                builder.addLap(500, 1500.0f, 100);
            }
            time++;
        }
        builder.addStatus(TtbinFileDefinition.STATUS_PAUSED , TtbinFileDefinition.ACTIVITY_RUNNING, time);
        builder.addStatus(TtbinFileDefinition.STATUS_STOPPED, TtbinFileDefinition.ACTIVITY_RUNNING, time);
        builder.addSummary(TtbinFileDefinition.ACTIVITY_RUNNING, 1800.0f, 600, 120);
        return builder.toUsbFile();
    }
}
